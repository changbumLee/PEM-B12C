"""
SSB curvature calibration — PEM Cityscapes scale-jitter matched version.

Key difference from the original calibration script:
- Samples PEM's Cityscapes MIN_SIZE_TRAIN choice for every TRAIN GT image.
- Applies Detectron2-style ResizeShortestEdge with MAX_SIZE_TRAIN=4096.
- Uses nearest-neighbor interpolation for semantic labels.
- Computes pooled Q95 curvature references on the resized GT distribution.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from PIL import Image

try:
    from .contour import extract_class_contours
    from .curvature import multiscale_raw_curvature
except ImportError:
    from contour import extract_class_contours
    from curvature import multiscale_raw_curvature


# Exact values generated by PEM Cityscapes base config:
# [int(x * 0.1 * 1024) for x in range(5, 21)]
PEM_CITYSCAPES_MIN_SIZE_TRAIN = (
    512,
    614,
    716,
    819,
    921,
    1024,
    1126,
    1228,
    1331,
    1433,
    1536,
    1638,
    1740,
    1843,
    1945,
    2048,
)
PEM_CITYSCAPES_MAX_SIZE_TRAIN = 4096


def parse_int_list(text: str, *, name: str) -> List[int]:
    values = [int(x.strip()) for x in text.split(",") if x.strip()]
    if not values or any(v < 1 for v in values):
        raise ValueError(f"{name} must contain positive integers")
    return values


def parse_radii(text: str) -> List[int]:
    return parse_int_list(text, name="radii")


class BoundedSamplePool:
    """Memory-bounded approximate random pool for percentile calibration."""

    def __init__(self, max_samples: int, rng: np.random.Generator):
        self.max_samples = int(max_samples)
        self.rng = rng
        self.chunks: List[np.ndarray] = []
        self.size = 0

    def add(self, values: np.ndarray) -> None:
        x = np.asarray(values, dtype=np.float32)
        x = x[np.isfinite(x)]
        if x.size == 0:
            return

        if x.size > self.max_samples:
            idx = self.rng.choice(x.size, size=self.max_samples, replace=False)
            x = x[idx]

        self.chunks.append(x)
        self.size += x.size

        if self.size > 2 * self.max_samples:
            merged = np.concatenate(self.chunks)
            idx = self.rng.choice(merged.size, size=self.max_samples, replace=False)
            kept = merged[idx]
            self.chunks = [kept]
            self.size = kept.size

    def array(self) -> np.ndarray:
        if not self.chunks:
            return np.empty(0, dtype=np.float32)

        merged = np.concatenate(self.chunks)
        if merged.size <= self.max_samples:
            return merged

        idx = self.rng.choice(merged.size, size=self.max_samples, replace=False)
        return merged[idx]


def find_train_gt_files(root: Path) -> List[Path]:
    candidates = [
        root / "gtFine" / "train",
        root / "gtFine_trainvaltest" / "gtFine" / "train",
    ]

    files: List[Path] = []
    for directory in candidates:
        if directory.exists():
            files.extend(sorted(directory.rglob("*_gtFine_labelTrainIds.png")))

    if not files:
        files = sorted(root.rglob("*_gtFine_labelTrainIds.png"))
        files = [path for path in files if "train" in path.parts]

    return files


def resize_shortest_edge_shape(
    height: int,
    width: int,
    short_edge_length: int,
    max_size: int,
) -> Tuple[int, int]:
    """Match Detectron2 ResizeShortestEdge output-size calculation."""
    height = int(height)
    width = int(width)
    short_edge_length = int(short_edge_length)
    max_size = int(max_size)

    scale = short_edge_length / float(min(height, width))
    new_h = height * scale
    new_w = width * scale

    if max(new_h, new_w) > max_size:
        cap_scale = max_size / float(max(new_h, new_w))
        new_h *= cap_scale
        new_w *= cap_scale

    return int(new_h + 0.5), int(new_w + 0.5)


def resize_label_shortest_edge(
    gt: np.ndarray,
    short_edge_length: int,
    max_size: int,
) -> Tuple[np.ndarray, Tuple[int, int]]:
    """Resize semantic label map with nearest-neighbor interpolation."""
    if gt.ndim != 2:
        raise ValueError(f"Expected HxW label map, got shape={gt.shape}")

    h, w = gt.shape
    new_h, new_w = resize_shortest_edge_shape(
        h,
        w,
        short_edge_length=short_edge_length,
        max_size=max_size,
    )

    if (new_h, new_w) == (h, w):
        return gt, (new_h, new_w)

    # labelTrainIds values are uint8 (0..18, 255). Nearest preserves IDs.
    pil = Image.fromarray(gt.astype(np.uint8, copy=False))
    resized = pil.resize((new_w, new_h), resample=Image.Resampling.NEAREST)
    return np.asarray(resized, dtype=np.int32), (new_h, new_w)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cityscapes-root", default="datasets/cityscapes")
    parser.add_argument(
        "--output",
        default="research/shape_ssb/geometry/curvature_reference_q95.json",
    )
    parser.add_argument("--radii", default="2,4,8")
    parser.add_argument("--percentile", type=float, default=95.0)
    parser.add_argument("--max-samples-per-scale", type=int, default=2_000_000)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--num-classes", type=int, default=19)
    parser.add_argument("--ignore-label", type=int, default=255)
    parser.add_argument("--min-contour-points", type=int, default=16)

    # Match PEM Cityscapes training ResizeShortestEdge distribution by default.
    parser.add_argument(
        "--resize-shortest-edge",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Apply PEM-style random ResizeShortestEdge before curvature extraction.",
    )
    parser.add_argument(
        "--min-size-train",
        default=",".join(map(str, PEM_CITYSCAPES_MIN_SIZE_TRAIN)),
        help="Discrete short-edge choices used by PEM Cityscapes training.",
    )
    parser.add_argument(
        "--max-size-train",
        type=int,
        default=PEM_CITYSCAPES_MAX_SIZE_TRAIN,
    )

    args = parser.parse_args()

    if not (0 < args.percentile <= 100):
        raise ValueError("percentile must be in (0,100]")

    radii = parse_radii(args.radii)
    min_size_train = parse_int_list(args.min_size_train, name="min-size-train")

    gt_files = find_train_gt_files(Path(args.cityscapes_root))
    if not gt_files:
        raise FileNotFoundError("No Cityscapes TRAIN labelTrainIds files found")

    print(f"Found {len(gt_files)} TRAIN GT images")

    # Keep augmentation-scale sampling independent from curvature-pool sampling.
    seed_seq = np.random.SeedSequence(args.seed)
    resize_seed, pool_seed = seed_seq.spawn(2)
    resize_rng = np.random.default_rng(resize_seed)
    pool_root_rng = np.random.default_rng(pool_seed)

    pools: Dict[int, BoundedSamplePool] = {}
    for r in radii:
        # Independent RNG per radius avoids coupling pool resampling across scales.
        child_seed = int(pool_root_rng.integers(0, np.iinfo(np.uint32).max, dtype=np.uint32))
        pools[r] = BoundedSamplePool(
            args.max_samples_per_scale,
            np.random.default_rng(child_seed),
        )

    resize_counts: Counter[int] = Counter()
    resized_shape_counts: Counter[str] = Counter()

    if args.resize_shortest_edge:
        print(
            "Calibration resize: PEM-style ResizeShortestEdge "
            f"choice={min_size_train}, max_size={args.max_size_train}"
        )
    else:
        print("Calibration resize: DISABLED (original GT resolution)")

    for i, gt_path in enumerate(gt_files, 1):
        gt = np.asarray(Image.open(gt_path), dtype=np.int32)

        if args.resize_shortest_edge:
            sampled_short_edge = int(resize_rng.choice(min_size_train))
            gt, resized_shape = resize_label_shortest_edge(
                gt,
                short_edge_length=sampled_short_edge,
                max_size=args.max_size_train,
            )
            resize_counts[sampled_short_edge] += 1
            resized_shape_counts[f"{resized_shape[0]}x{resized_shape[1]}"] += 1

        for c in range(args.num_classes):
            for contour in extract_class_contours(
                gt,
                c,
                args.ignore_label,
                args.min_contour_points,
            ):
                raw = multiscale_raw_curvature(contour, radii)
                for r in radii:
                    pools[r].add(raw[r])

        if i == 1 or i % 100 == 0:
            suffix = ""
            if args.resize_shortest_edge:
                suffix = f" short_edge={sampled_short_edge} resized={gt.shape[0]}x{gt.shape[1]}"
            print(f"[{i}/{len(gt_files)}] {gt_path.name}{suffix}")

    refs: Dict[str, float] = {}
    counts: Dict[str, int] = {}

    for r in radii:
        vals = pools[r].array()
        if vals.size == 0:
            raise RuntimeError(f"No valid curvature samples for radius {r}")

        q = float(np.percentile(vals, args.percentile))
        if q <= 0:
            raise RuntimeError(f"Non-positive reference for radius {r}: {q}")

        refs[f"r{r}"] = q
        counts[f"r{r}"] = int(vals.size)
        print(f"r={r}: Q{args.percentile:g}={q:.8f} samples={vals.size:,}")

    if args.resize_shortest_edge:
        print("Resize choice counts:")
        for size in min_size_train:
            print(f"  short_edge={size}: {resize_counts[size]}")

    output = {
        "dataset": "Cityscapes",
        "split": "train",
        "percentile": float(args.percentile),
        "radii": radii,
        "seed": int(args.seed),
        "max_samples_per_scale": int(args.max_samples_per_scale),
        "min_contour_points": int(args.min_contour_points),
        "ignore_label": int(args.ignore_label),
        "calibration_geometry": {
            "resize_shortest_edge": bool(args.resize_shortest_edge),
            "min_size_train_sampling": "choice" if args.resize_shortest_edge else None,
            "min_size_train": min_size_train if args.resize_shortest_edge else None,
            "max_size_train": int(args.max_size_train) if args.resize_shortest_edge else None,
            "interpolation": "nearest" if args.resize_shortest_edge else None,
            "crop_applied": False,
            "flip_applied": False,
            "note": (
                "Resize distribution matched to PEM Cityscapes training. "
                "Crop/flip are intentionally omitted from global curvature calibration; "
                "flip preserves curvature magnitude and crop context is handled by halo geometry."
                if args.resize_shortest_edge
                else "Original-resolution calibration."
            ),
        },
        "resize_choice_counts": {
            str(k): int(v) for k, v in sorted(resize_counts.items())
        },
        "resized_shape_counts": {
            k: int(v) for k, v in sorted(resized_shape_counts.items())
        },
        "references": refs,
        "sample_counts": counts,
    }

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(output, indent=2), encoding="utf-8")
    print(f"Saved: {output_path}")


if __name__ == "__main__":
    main()
